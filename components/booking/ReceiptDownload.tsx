"use client";
import { useState } from "react";
import { downloadBookingReceipt } from "@/lib/api/bookings";
import { documentErrorMessage } from "@/lib/api/document-error";

export default function ReceiptDownload({ bookingId }: { bookingId: string }) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function download() {
    setBusy(true); setError("");
    try { await downloadBookingReceipt(bookingId); }
    catch (reason) { setError(documentErrorMessage(reason, "receipt")); }
    finally { setBusy(false); }
  }
  return <section className="mt-6 border-t border-rule pt-5" aria-busy={busy}>
    <div className="label">Booking receipt</div>
    <p className="mt-2 text-sm text-ink/75">Payment receipts are generated by Eema from the confirmed booking record.</p>
    <p className="mt-1 text-xs text-taupe">This is a payment record, not a tax invoice.</p>
    <button type="button" className="btn btn-ochre mt-4" disabled={busy} onClick={() => void download()} aria-label="Download booking receipt">
      {busy ? "Preparing receipt…" : "Download receipt"}
    </button>
    {error && <p className="mt-3 text-sm text-red-800" role="alert">{error}</p>}
  </section>;
}
